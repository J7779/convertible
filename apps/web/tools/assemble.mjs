// Convertible web app - assembles the static site in dist/ from the sources,
// the compiled core and the shared brand assets (which are copied, never
// duplicated in git). Zero dependencies; runs with any Node 18+.
//
//   node apps/web/tools/assemble.mjs --repo . --wasm-dir apps/web/build/wasm --out apps/web/dist
//
