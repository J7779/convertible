import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { buildManifest, injectManifest } from './precache.mjs';

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : fallback;
}

const webDir = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const repo = path.resolve(arg('repo', path.join(webDir, '..', '..')));
const wasmDir = path.resolve(arg('wasm-dir', path.join(webDir, 'build', 'wasm')));
const out = path.resolve(arg('out', path.join(webDir, 'dist')));
const src = path.join(webDir, 'src');
const brand = path.join(repo, 'assets', 'brand');
const fonts = path.join(repo, 'assets', 'fonts');

async function appVersion() {
  const cmake = await readFile(path.join(webDir, 'CMakeLists.txt'), 'utf8');
  return /project\(ConvertibleWeb VERSION ([0-9.]+)/.exec(cmake)?.[1] ?? '0.0.0';
}

async function copy(from, to) {
  await mkdir(path.dirname(to), { recursive: true });
  await cp(from, to, { recursive: true });
}

async function main() {
  await rm(out, { recursive: true, force: true });
  await mkdir(out, { recursive: true });

  // 1. Application sources (HTML, CSS, JS modules, service worker template).
  await cp(src, out, {
    recursive: true,
    filter: (p) => !p.endsWith('manifest.template.json') && !p.endsWith('.DS_Store'),
  });

  // 2. The compiled core.
  await copy(path.join(wasmDir, 'convertible.mjs'), path.join(out, 'wasm', 'convertible.mjs'));
  await copy(path.join(wasmDir, 'convertible.wasm'), path.join(out, 'wasm', 'convertible.wasm'));

  // 3. Brand assets: tokens, fonts (+ licences), icons.
  await copy(path.join(brand, 'tokens.css'), path.join(out, 'assets', 'brand', 'tokens.css'));
  for (const f of ['Inter-Regular.ttf', 'Inter-Medium.ttf', 'Inter-SemiBold.ttf', 'JetBrainsMonoNL-Regular.ttf', 'JetBrainsMonoNL-Medium.ttf']) {
    await copy(path.join(fonts, f), path.join(out, 'assets', 'fonts', f));
  }
  const icons = ['favicon.svg', 'favicon.ico', 'icon-180.png', 'icon-192.png', 'icon-512.png', 'icon-maskable-192.png', 'icon-maskable-512.png'];
  for (const f of icons) await copy(path.join(brand, 'icons', f), path.join(out, 'assets', 'brand', 'icons', f));

  // 4. Licences and notices shown on the About screen.
  await copy(path.join(repo, 'LICENSE'), path.join(out, 'legal', 'LICENSE.txt'));
  await copy(path.join(fonts, 'Inter-LICENSE.txt'), path.join(out, 'legal', 'Inter-LICENSE.txt'));
  await copy(path.join(fonts, 'JetBrainsMono-LICENSE.txt'), path.join(out, 'legal', 'JetBrainsMono-LICENSE.txt'));
  // The core compiled to WebAssembly contains imported codecs and embedded fonts.
  await copy(path.join(repo, 'NOTICES.md'), path.join(out, 'legal', 'NOTICES.txt'));

  // 5. Motion storyboard as an ES module (no fetch needed at start-up).
  const animation = JSON.parse(await readFile(path.join(brand, 'animation.json'), 'utf8'));
  await mkdir(path.join(out, 'js', 'generated'), { recursive: true });
  await writeFile(
    path.join(out, 'js', 'generated', 'animation.js'),
    `// Generated from assets/brand/animation.json by tools/assemble.mjs. Do not edit.\nexport default ${JSON.stringify(animation)};\n`,
  );

  // 6. Ask the real core for its catalogue: file handlers cover every readable format.
  const { default: factory } = await import(pathToFileURL(path.join(out, 'wasm', 'convertible.mjs')).href);
  const { ConvertibleCore } = await import(pathToFileURL(path.join(out, 'js', 'core', 'binding.js')).href);
  const { fileHandlers } = await import(pathToFileURL(path.join(out, 'js', 'model', 'targets.js')).href);
  const wasmBinary = await readFile(path.join(out, 'wasm', 'convertible.wasm'));
  const core = await ConvertibleCore.create(factory, { wasmBinary });
  const formats = core.formats();
  const version = await appVersion();
  await writeFile(
    path.join(out, 'js', 'generated', 'build-info.js'),
    `// Generated by tools/assemble.mjs. Do not edit.\nexport const APP_VERSION = ${JSON.stringify(version)};\nexport const CORE_VERSION = ${JSON.stringify(core.version())};\n` +
      `// Uncompressed size of wasm/convertible.wasm: the download progress total.\nexport const CORE_WASM_BYTES = ${wasmBinary.length};\n`,
  );

  // The catalogue as data: the page shows formats, counts and the browser
  // without waiting for the ~30 MB core to download and compile.
  await writeFile(path.join(out, 'catalogue.json'), JSON.stringify({ version: core.version(), formats }));

  const manifest = JSON.parse(await readFile(path.join(src, 'manifest.template.json'), 'utf8'));
  manifest.file_handlers = fileHandlers(formats, { icons: [{ src: 'assets/brand/icons/icon-192.png', sizes: '192x192', type: 'image/png' }] });
  await writeFile(path.join(out, 'manifest.webmanifest'), `${JSON.stringify(manifest, null, 2)}\n`);

  // 7. Service worker with the precache manifest of everything above.
  const precache = await buildManifest(out);
  const template = await readFile(path.join(src, 'sw.js'), 'utf8');
  await writeFile(path.join(out, 'sw.js'), injectManifest(template, precache));

  const total = precache.files.reduce((a, f) => a + f.size, 0);
  const wasm = precache.files.find((f) => f.url.endsWith('.wasm'));
  console.log(`dist: ${precache.files.length + 1} files, ${(total / 1e6).toFixed(2)} MB precached (wasm ${(wasm.size / 1e6).toFixed(2)} MB), cache ${precache.version}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
