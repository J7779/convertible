/// Quantisation class of a Layer I/II allocation: `levels` steps, either
/// `bits` per sample or, when `grouped`, three samples in one `bits`-bit code.
struct QuantClass {
  std::uint16_t levels;
  std::uint8_t bits;
  bool grouped;
};

/// Index -> class: 0 none, 1: 3 levels grouped, 2: 5 grouped, 3: 7, 4: 9
/// grouped, 5: 15, 6: 31, ... 17: 65535.
inline constexpr QuantClass quant_classes[18] = {
    {0, 0, false},     {3, 5, true},      {5, 7, true},      {7, 3, false},     {9, 10, true},
    {15, 4, false},    {31, 5, false},    {63, 6, false},    {127, 7, false},   {255, 8, false},
    {511, 9, false},   {1023, 10, false}, {2047, 11, false}, {4095, 12, false}, {8191, 13, false},
    {16383, 14, false}, {32767, 15, false}, {65535, 16, false},
};

/// One row of a Layer II allocation table: subbands that share the number of
/// allocation bits and the list of quantisation classes (indices into
/// quant_classes) that the allocation code selects.
struct AllocRow {
  std::uint8_t subbands;
  std::uint8_t alloc_bits;
  std::uint8_t classes[16];
};

